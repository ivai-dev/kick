"""`kickoff export`: the WBS as files any tracker can import (CSV, JSON, Markdown).

One record per package, in plan order, with the baseline dates. The output is deterministic (no timestamps), so a
re-export after a plan change diffs cleanly."""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path

from .model import Features, Plan, Project, text
from .schedule import build_schedule

FORMATS = ("csv", "json", "md")
FILES = {"csv": "wbs.csv", "json": "wbs.json", "md": "wbs-items.md"}
FIELDS = ["code", "name", "phase", "group", "role", "effort", "deps", "release", "prio", "features", "start", "end",
          "type", "title", "epic", "areas", "desc", "ac", "sprint", "effort_min", "effort_max", "confidence"]
LIST_FIELDS = {"deps", "features", "areas", "ac"}


def _num(value: float) -> int | float:
    return int(value) if float(value).is_integer() else value


def _node_names(nodes: list[dict], lang: str | None) -> dict[str, str]:
    return {str(n["code"]): text(n, "name", lang) for n in nodes}


def _features_of(code: str, ref: str, features: Features) -> list[str]:
    out = []
    for f in features.all():
        if f.status != "active":
            continue
        if any(code == w or code.startswith(w + ".") for w in f.wbs) or f.id in ref.split():
            out.append(f.id)
    return out


def records(project: Project, plan: Plan, features: Features, lang: str | None = None) -> list[dict]:
    """The export rows: plan text in the plan's language, or its `lang` translation where one exists."""
    sched = build_schedule(project, plan, baseline=True)
    phases, groups = _node_names(plan.phases, lang), _node_names(plan.groups, lang)
    rows = []
    for p in plan.packages:
        item = p.item or {}
        parts = p.code.split(".")
        slot = sched.slots.get(p.code)
        effort = _num(p.effort)
        rows.append({
            "code": p.code,
            "name": text(p.as_item(), "name", lang),
            "phase": phases.get(parts[0], ""),
            "group": groups.get(".".join(parts[:2]), "") if len(parts) > 2 else "",
            "role": project.role_title(p.role, lang) if p.role in project.roles else p.role,
            "effort": effort,
            "deps": list(p.deps),
            "release": p.release or "",
            "prio": p.prio,
            "features": _features_of(p.code, p.ref, features),
            "start": slot.start.isoformat() if slot else "",
            "end": slot.end.isoformat() if slot else "",
            "type": item.get("type", ""),
            "title": item.get("title") or text(p.as_item(), "name", lang),
            "epic": item.get("epic", ""),
            "areas": list(item.get("areas") or []),
            "desc": item.get("desc") or text(p.as_item(), "desc", lang),
            "ac": list(item.get("ac") or []),
            "sprint": item.get("sprint", ""),
            "effort_min": _num(p.effort if p.effort_min is None else p.effort_min),
            "effort_max": _num(p.effort if p.effort_max is None else p.effort_max),
            "confidence": p.confidence,
        })
    return rows


def to_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=FIELDS, lineterminator="\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({k: "; ".join(map(str, v)) if k in LIST_FIELDS else v for k, v in row.items()})
    return buf.getvalue()


def to_json(project: Project, rows: list[dict], lang: str) -> str:
    total = sum(float(r["effort"]) for r in rows)
    doc = {"project": project.name, "source": "plan.yaml (baseline schedule)", "language": lang,
           "effort_unit": "person-days at 100% focus", "total_effort": round(total, 2), "items": rows}
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def to_md(project: Project, rows: list[dict]) -> str:
    out = [f"# {project.name}: work items", "",
           f"{len(rows)} packages from `plan.yaml`, baseline dates. Generated by `kickoff export`; edit the plan, "
           "not this file.", ""]
    for r in rows:
        out += [f"## {r['code']} {r['title']}", ""]
        spread = f"{r['effort_min']} to {r['effort_max']}" if r["effort_min"] != r["effort_max"] else ""
        facts = [("Role", r["role"]), ("Effort (pd)", r["effort"]), ("Range (pd)", spread),
                 ("Confidence", r["confidence"]), ("Dates", f"{r['start']} → {r['end']}"),
                 ("Depends on", ", ".join(r["deps"])), ("Release", r["release"]), ("Priority", r["prio"]),
                 ("Features", ", ".join(r["features"])), ("Epic", r["epic"]), ("Type", r["type"]),
                 ("Sprint", r["sprint"]), ("Areas", ", ".join(r["areas"]))]
        out += ["| Field | Value |", "| --- | --- |"]
        out += [f"| {k} | {v} |" for k, v in facts if v not in ("", None)]
        out.append("")
        if r["desc"]:
            out += [r["desc"], ""]
        if r["ac"]:
            out += ["Acceptance criteria:", "", *[f"- [ ] {a}" for a in r["ac"]], ""]
    return "\n".join(out)


def export(project: Project, plan: Plan, features: Features, out: Path, formats: list[str],
           lang: str | None = None) -> list[Path]:
    rows = records(project, plan, features, lang)
    language = lang or project.languages.get("workbook", "en")
    render = {"csv": lambda: to_csv(rows), "json": lambda: to_json(project, rows, language),
              "md": lambda: to_md(project, rows)}
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for fmt in formats:
        path = out / FILES[fmt]
        # Excel opens a UTF-8 CSV with a BOM correctly (Vietnamese text); other files stay plain UTF-8.
        path.write_text(render[fmt](), encoding="utf-8-sig" if fmt == "csv" else "utf-8", newline="\n")
        written.append(path)
    return written
