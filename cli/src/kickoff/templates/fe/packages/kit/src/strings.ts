const dictionaries: Record<string, KitStrings> = { en, vi };

export function kitStrings(lang: string): KitStrings {
  return dictionaries[lang.split("-")[0]?.toLowerCase() ?? "en"] ?? en;
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
